import { createHash } from 'node:crypto';
import { basename } from 'node:path';
import { validateWorkflowRecord } from './canonical-validation.mjs';
import { stageResources, stageTargets } from './orchestration-resources.mjs';
import {
  currentTaskForRecord, executionKind, implementationAllowed, latestVerification, taskSummary,
} from './orchestration-routing.mjs';
import { stageTransitionPolicy } from './stage-transition-policy.mjs';
import { toolkitBindingFromRecord } from './toolkit-binding.mjs';
import { deriveNextAction, readyTask } from './workflow-actions.mjs';
import { STAGES } from './workflow-model.mjs';

export const AGENT_PROJECTION_VERSION = 4;
export const AGENT_PROJECTION_FILE = 'AGENT-CONTEXT.json';

function workflowRecordGitBlobSha(record) {
  const bytes = Buffer.from(`${JSON.stringify(record, null, 2)}\n`, 'utf8');
  const header = Buffer.from(`blob ${bytes.length}\0`, 'utf8');
  return createHash('sha1').update(header).update(bytes).digest('hex');
}

function targetArtifacts(record, targets) {
  return record.artifacts
    .filter((artifact) => artifact.status !== 'Superseded' && targets.includes(artifact.type))
    .map((artifact) => ({
      id: artifact.id,
      type: artifact.type,
      path: artifact.path,
      status: artifact.status,
      baseline: artifact.baseline,
      approvedRevision: artifact.approvedRevision ?? null,
    }));
}

function workflowMutationPolicy(record, valid) {
  if (record.schemaVersion === 1) return 'migration-required-via-cli';
  if (!valid) return 'repair-required-via-cli';
  return 'cli-required';
}

function portableImplementationPolicy(authorized) {
  return {
    implementationAuthorization: authorized ? 'current-task-authorized' : 'forbidden',
    implementationIntegrity: authorized ? 'runtime-verification-required-before-editing' : 'not-applicable',
    implementation: authorized ? 'allowed-after-source-integrity-check' : 'forbidden',
    codeEdits: authorized ? 'allowed-after-source-integrity-check' : 'forbidden',
  };
}

export function buildAgentProjection(recordPath, record, recordDigest) {
  const recordFindings = validateWorkflowRecord(record);
  const valid = recordFindings.length === 0;
  const toolkit = toolkitBindingFromRecord(record);
  const targets = stageTargets(record);
  const currentTask = currentTaskForRecord(record);
  const nextReadyTask = readyTask(record) ?? null;
  const resources = stageResources(record, toolkit);
  const codeEditsAuthorized = implementationAllowed(record, {
    workflowValid: valid,
    currentTask,
  });
  const nextAction = deriveNextAction(record);
  const stageTransition = stageTransitionPolicy(record, {
    workflowValid: valid,
    cliAvailable: false,
  });

  return {
    generated: {
      notice: 'Generated by @ferfalcon/design-workflow. Do not edit manually.',
      projectionVersion: AGENT_PROJECTION_VERSION,
      record: `../${basename(recordPath)}`,
      recordSha256: recordDigest,
      recordGitBlobSha: workflowRecordGitBlobSha(record),
      purpose: 'Portable read-only routing context for agents that can read GitHub but cannot execute design-workflow.',
    },
    initialized: true,
    control: {
      mode: 'cli-managed',
      schemaVersion: record.schemaVersion,
      readOnly: record.schemaVersion !== 2,
    },
    project: {
      name: record.project.name,
      profile: record.project.profile,
      executionMode: record.project.executionMode,
    },
    toolkit,
    workflow: {
      recordValidAtGeneration: valid,
      recordFindings,
      runtimeIntegrity: 'not-evaluated-in-portable-projection',
    },
    state: {
      profile: record.project.profile,
      mode: record.project.executionMode,
      stage: record.state.stage,
      stageName: STAGES[record.state.stage] ?? 'Unknown stage',
      stageStatus: record.state.status,
      executionKind: executionKind(record, { workflowValid: valid }),
      architectureDecision: record.state.architectureDecision ?? null,
      profileTransition: record.profileTransitions?.find((item) => item.status === 'In progress') ?? null,
    },
    policy: {
      workflowMutation: workflowMutationPolicy(record, valid),
      ...portableImplementationPolicy(codeEditsAuthorized),
      stageTransition,
      generatedViews: 'read-only-projections',
      workflowReads: 'generated-agent-context-resource-manifest-only',
      toolkitReads: toolkit.pinned && !toolkit.ambiguous && !toolkit.invalid && !toolkit.legacy
        ? 'exact-pinned-source-only'
        : 'pin-migrate-or-repair-before-remote-resource-use',
    },
    task: {
      instruction: nextAction,
      artifactTypes: targets,
      artifacts: targetArtifacts(record, targets),
      current: currentTask,
      ready: record.tasks.filter((task) => task.status === 'Ready').map(taskSummary),
      nextReady: nextReadyTask ? nextReadyTask.id : null,
    },
    sources: {
      active: record.state.activeInputs.map((id) => {
        const snapshot = record.snapshots.find((item) => item.id === id);
        return snapshot ? { ...snapshot, latestVerification: latestVerification(record, id) } : { id, missing: true };
      }),
      latestOutput: record.state.latestOutput,
      latestValidationRuntime: record.state.latestValidationRuntime ?? null,
    },
    resources: {
      ...resources,
      sourceAdapterPolicy: 'Select only the conditional source adapter matching the actual source. Use exact pinned toolkit locations when provided.',
    },
    nextAction,
  };
}

export function renderAgentProjection(recordPath, record, recordDigest) {
  return `${JSON.stringify(buildAgentProjection(recordPath, record, recordDigest), null, 2)}\n`;
}
